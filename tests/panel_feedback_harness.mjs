import fs from 'fs';
import {JSDOM, VirtualConsole} from 'jsdom';
const errors=[], requests=[], copied=[];
const vc=new VirtualConsole(); vc.on('jsdomError', e=>errors.push(e));
const dom=new JSDOM(fs.readFileSync(process.argv[2],'utf8'), {url:'http://localhost/panel.html',runScripts:'dangerously',virtualConsole:vc,beforeParse(w){
  w.fetch=(url)=>{requests.push(String(url));return Promise.reject(new Error('offline fixture'));};
  Object.defineProperty(w.navigator,'clipboard',{value:{writeText:async text=>{copied.push(text);}}, configurable:true});
}});
const w=dom.window,d=w.document;
const pause=()=>new Promise(resolve=>setTimeout(resolve,70));
function check(ok, label){if(!ok) throw new Error(label);console.log('PASS '+label);}
function fill(id,value){const el=d.getElementById(id);el.value=value;el.dispatchEvent(new w.Event('input',{bubbles:true}));}
await pause();
check(d.getElementById('btn-feedback'),'feedback entry exists');
d.getElementById('btn-feedback').click();
check(d.getElementById('feedback-modal').classList.contains('open'),'feedback works with bridge offline');
const initialRequests=requests.length;
check(!d.getElementById('feedback-mail').hasAttribute('href'),'empty feedback cannot open mail');
fill('feedback-title','更新后模块丢失 &bcc=wrong@example.invalid');
fill('feedback-details','操作：选择模块后更新\n预期：模块仍可使用\n<script>window.feedbackInjected=true</script>');
fill('feedback-tool','codex');
const mail=new URL(d.getElementById('feedback-mail').href);
check(mail.protocol==='mailto:' && mail.pathname==='fushengsan3@gmail.com','fixed recipient');
check(mail.searchParams.size===2 && !mail.searchParams.has('bcc'),'subject cannot inject mail recipients');
check(mail.searchParams.get('subject').includes('[问题反馈][无核版]'),'subject carries category and edition for mailbox grouping');
check(mail.searchParams.get('body').includes('Codex') && mail.searchParams.get('body').includes('操作：选择模块后更新'),'only selected fields compose the message');
check(!mail.href.includes('PRIVATE-BRIDGE-KEY') && !mail.href.includes('LOCAL_DATA_NOT_FOR_FEEDBACK'),'private panel data excluded');
check(!w.feedbackInjected,'feedback stays plain text');
check(d.getElementById('feedback-preview').value===mail.searchParams.get('body'),'preview exactly matches mail body');
d.getElementById('feedback-copy').click(); await pause();
check(copied.length===1 && copied[0].includes('fushengsan3@gmail.com') && copied[0].includes('操作：选择模块后更新'),'copy fallback includes recipient subject and body');
const stored=Array.from({length:w.localStorage.length},(_,i)=>w.localStorage.getItem(w.localStorage.key(i))).join('');
check(!stored.includes('操作：选择模块后更新'),'feedback is not persisted automatically');
check(requests.length===initialRequests,'editing and copying cause no network requests');
const link=d.getElementById('feedback-mail');link.addEventListener('click',e=>e.preventDefault());link.click();
check(d.getElementById('feedback-status').textContent.includes('无法确认送达'),'opening mail does not claim successful delivery');
Object.defineProperty(w.navigator,'clipboard',{value:{writeText:async()=>{throw new Error('denied');}}, configurable:true});
d.getElementById('feedback-copy').click(); await pause();
check(d.getElementById('feedback-status').textContent.includes('手动复制'),'clipboard failure offers manual copying');
d.getElementById('btn-en').click();
check(d.getElementById('feedback-heading').textContent==='Send feedback','English labels');
check(d.getElementById('feedback-preview').value.includes('Coreless'),'preview reflects the current language');
fill('feedback-details','x'.repeat(1801));
check(!d.getElementById('feedback-mail').hasAttribute('href'),'oversized input rejected even when set programmatically');
fill('feedback-details','   ');
check(d.getElementById('feedback-copy').disabled,'whitespace feedback rejected');
d.getElementById('feedback-modal').dispatchEvent(new w.KeyboardEvent('keydown',{key:'Escape',bubbles:true}));
check(!d.getElementById('feedback-modal').classList.contains('open') && d.activeElement.id==='btn-feedback','Escape closes and restores focus');
check(errors.length===0,'no panel runtime errors');
dom.window.close();
